export interface WorldCountryEntry {
  code: string;        // ISO 3166-1 alpha-2 e.g. 'LK'
  name: string;        // Official common English country name
  dialCode: string;    // International dial prefix e.g. '+94'
  dialDigits: string;  // Digits only e.g. '94'
  flag: string;        // Unicode emoji flag
  defaultCurrency: string;      // Primary currency symbol/code used in workspace
  currencyLabel: string;        // Descriptive currency label
  timezones?: string[];         // Common IANA timezone identifiers
}

const isoToFlag = (isoCode: string): string => {
  const clean = isoCode.trim().toUpperCase();
  if (clean.length !== 2) return '🌐';
  return String.fromCodePoint(
    127397 + clean.charCodeAt(0),
    127397 + clean.charCodeAt(1)
  );
};

